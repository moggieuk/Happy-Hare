class Parser(object):
    def __init__(self, default_assign_op=":", default_comment_ch="#", recover=True, error_marker=True):
        self.origin = None
        self.default_assign_op = default_assign_op
        self.default_comment_ch = default_comment_ch
        self.recover = recover              # keep going after a syntax error instead of raising
        self.error_marker = error_marker    # leave a marker comment in the config at the bad spot
        self.recoveries = 0

    def _syntax_error(self, tokenizer, message, peek=None, include_token=True):
        if peek is not None and getattr(peek, "line", None) is not None:
            line = peek.line
            col = peek.col
        else:
            line = getattr(tokenizer, "line", None)
            col = getattr(tokenizer, "col", None)

        origin = self.origin or getattr(tokenizer, "origin", None)

        token_info = " '{}'".format(peek) if peek is not None and include_token else ""
        ctx = tokenizer._format_error_context(line, col, origin) if hasattr(tokenizer, "_format_error_context") else ""
        raise ConfigSyntaxError("{}{}".format(message, token_info), line, col, origin, ctx)

    def parse(self, buffer, origin=None):
        self.origin = origin
        self.recoveries = 0
        tokenizer = Tokenizer(buffer, CONFIG_SPEC, origin=origin)
        return self._post_process(self.parse_document(tokenizer))

    def _recover(self, tokenizer, err, start_pos):
        """
        Turn a syntax error into a reported-but-survivable one. Everything from the start of
        the failing construct up to the next section/option is kept verbatim in an
        UnparsedNode, followed by a marker comment so the user can find it in the file.

        The marker goes *after* the skipped text, on a line of its own: a comment there is
        always legal to Klipper, whereas inserting one ahead of a partially consumed line
        would rewrite the meaning of that line.
        """
        self.recoveries += 1
        if not self.recover:
            raise err

        # A config this broken isn't worth chasing line by line - keep the rest verbatim
        give_up = self.recoveries > MAX_RECOVERIES
        text = tokenizer.resync(start_pos, to_eof=give_up)
        if give_up:
            logging.error("Too many parse errors - the remainder of the file was left unparsed")

        # Drop markers left by an earlier run so repeated builds don't stack them up
        without_markers = "\n".join([l for l in text.split("\n") if not l.lstrip().startswith(PARSE_ERROR_MARKER)])
        text = without_markers if without_markers.strip() else text
        if not text:
            return []

        reason = getattr(err, "reason", None) or unicode(err).splitlines()[0].strip()
        line = getattr(err, "line", None)
        origin = self.origin or getattr(tokenizer, "origin", None)

        logging.error("Unable to parse {}{}".format("{} ".format(origin) if origin else "", unicode(err)))
        logging.error(
            "Skipped {} unparsable line(s) from line {} and carried on".format(
                len(text.strip("\n").split("\n")), line
            )
        )

        nodes = [UnparsedNode(text, line=line, origin=origin, reason=reason)]
        if self.error_marker:
            if not text.endswith("\n"):
                nodes.append(WhitespaceNode("\n"))
            # Deliberately no line number in the marker: it has to survive a rebuild that
            # inserts an [include] above it without the text changing, or every install
            # would churn the user's config
            marker = "{}: {} - line(s) above left untouched, please fix".format(PARSE_ERROR_MARKER, reason)
            nodes.append(CommentNode([CommentEntryNode(marker)]))
            nodes.append(WhitespaceNode("\n"))
        return nodes

    def filter_tree(self, node, predicate):
        """
        Remove any node (and its subtree) for which predicate(node) is True.
        Operates in-place.
        """

        def _filter_tree(parent, cur):
            # If this node should be removed, prune it from the parent and stop descending.
            if predicate(cur):
                if isinstance(parent, BodyNode):
                    try:
                        parent.body.remove(cur)
                    except ValueError:
                        pass  # already removed or not present
                return

            # Otherwise descend into children if present.
            if isinstance(cur, BodyNode):
                for child in list(cur.body):  # iterate over a snapshot to avoid skipping
                    _filter_tree(cur, child)

        _filter_tree(None, node)

    def parse_document(self, tokenizer):
        def _parse_regular(peek, body):
            start_pos = peek.pos
            try:
                if peek.type == "section":
                    body.append(self.parse_section(tokenizer))
                elif peek.type == "hidden_option_comment":
                    body.append(self.parse_hidden_option_comment(tokenizer))
                elif peek.type == "comment":
                    body.append(self.parse_comment(tokenizer))
                elif peek.type == "whitespace":
                    body.append(self.parse_whitespace(tokenizer))
                elif peek.type == "placeholder":
                    body.append(self.parse_placeholder(tokenizer))
                elif peek.type == "template":
                    body.append(self.parse_template(tokenizer))
                else:
                    self._syntax_error(tokenizer, "Expected a [section], an option or a comment, got", peek)
            except SyntaxError as err:
                body.extend(self._recover(tokenizer, err, start_pos))

        body = []
        peek = tokenizer.peek()

        while peek:
            # Start exclusion block: the magic comment and then everything to EOF
            if _is_magic_comment_token(peek):
                magic_comment = self.parse_comment(tokenizer)  # Keep the marker as a real comment
                exclusion_body = [magic_comment]

                peek2 = tokenizer.peek()
                while peek2:
                    _parse_regular(peek2, exclusion_body)
                    peek2 = tokenizer.peek()

                body.append(MagicExclusionNode(exclusion_body, self.origin))
                break  # Everything else is now inside the exclusion node

            _parse_regular(peek, body)
            peek = tokenizer.peek()

        return DocumentNode(body)

    def _post_process(self, document):
        """Move trailing whitespace/comments from sections a level up to be part of the document body"""
        new_body = []
        for item in document.body:
            new_body.append(item)
            if isinstance(item, SectionNode):
                # Find the index of the next item after last option in the section
                idx = max([i + 1 for i, n in enumerate(item.body) if isinstance(n, OptionNode)] or [0])
                if len(item.body) <= idx:
                    continue
                # If the next item is whitespace, still keep it in the section
                if isinstance(item.body[idx], WhitespaceNode):
                    idx += 1
                # All remaining items get moved up a level
                if len(item.body) > idx:
                    new_body += item.body[idx:]
                    item.body = item.body[:idx]

        document.body = new_body
        return document

    def parse_section(self, tokenizer):
        token = tokenizer.take("section")
        body = []

        peek = tokenizer.peek()
        while peek and peek.type != "section":
            if _is_magic_comment_token(peek):
                break  # Do not consume here—let parse_document() handle it

            start_pos = peek.pos
            try:
                if peek.type == "hidden_option_comment":
                    body.append(self.parse_hidden_option_comment(tokenizer))
                elif peek.type == "comment":
                    body.append(self.parse_comment(tokenizer))
                elif peek.type == "word":
                    body.append(self.parse_option(tokenizer))
                elif peek.type == "placeholder":
                    body.append(self.parse_placeholder(tokenizer))
                elif peek.type == "whitespace":
                    body.append(self.parse_whitespace(tokenizer))
                elif peek.type == "template":
                    body.append(self.parse_template(tokenizer))
                else:
                    self._syntax_error(tokenizer, "Expected a [section], an option or a comment, got", peek)
            except SyntaxError as err:
                body.extend(self._recover(tokenizer, err, start_pos))
            peek = tokenizer.peek()

        return SectionNode(token.value[1:-1], body)

    def parse_option(self, tokenizer):
        token = tokenizer.take("word")
        trailing_ws = ""
        peek = tokenizer.peek()
        if peek is None:
            self._syntax_error(tokenizer, "Unexpected end of file after '{}'".format(token.value))
        if peek.type == "whitespace":
            trailing_ws = tokenizer.take("whitespace").value

        # Spelled out rather than left as a bare "Expected assign_op": this is the error a
        # user actually hits (e.g. an orphaned value line) and they have to act on it. Kept
        # short because it also ends up in the marker comment written into their config
        peek = tokenizer.peek()
        if peek is None or peek.type != "assign_op":
            self._syntax_error(
                tokenizer, "Expected ':' or '=' after '{}'".format(token.value), peek, include_token=False
            )
        assign_op = tokenizer.take("assign_op").value
        if token.value.startswith("gcode"):  # parse gcode options as-is, so we don't parse gcode as structure'
            value = self.parse_value(tokenizer, as_is=True)
        else:
            value = self.parse_value(tokenizer)

        return OptionNode(token.value, value, assign_op, trailing_ws)

    def _continues_after_comments(self, tokenizer, token):
        """
        Called where a multi-line value would normally end (a newline with nothing indented
        after it). Klipper's configparser treats a whole-line comment as invisible inside a
        value, so a value can be interrupted by commented out lines and still continue. E.g.

            points:
            ### 30, 5
                50, 10
                150, 225

        Peek past a run of comment-only lines and report whether an indented continuation
        line follows. Blank lines still end a value, as they always have here.
        """
        if token.value.count("\n") != 1:
            return False

        rest = tokenizer.slice  # text after the peeked newline, so starts at column 1 of a line
        pos = 0
        while pos < len(rest):
            eol = rest.find("\n", pos)
            line = rest[pos:] if eol == -1 else rest[pos:eol]
            if not COMMENT_ONLY_LINE.match(line):
                return CONTINUATION_LINE.match(line) is not None
            if eol == -1:
                return False
            pos = eol + 1
        return False

    def parse_value(self, tokenizer, as_is=False):
        body = []
        current_entry = ""
        current_line = []

        brace_depth = 0
        bracket_depth = 0
        paren_depth = 0
        in_sq = False
        in_dq = False
        esc = False

        # Helper to balance bracketing in multi-line config options
        def _scan_balance(s):
            nonlocal brace_depth, bracket_depth, paren_depth, in_sq, in_dq, esc
            for ch in s:
                if esc:
                    esc = False
                    continue
                if ch == "\\":
                    esc = True
                    continue
                if in_sq:
                    if ch == "'":
                        in_sq = False
                    continue
                if in_dq:
                    if ch == '"':
                        in_dq = False
                    continue
                if ch == "'":
                    in_sq = True
                elif ch == '"':
                    in_dq = True
                elif ch == "{":
                    brace_depth += 1
                elif ch == "}":
                    brace_depth = max(0, brace_depth - 1)
                elif ch == "[":
                    bracket_depth += 1
                elif ch == "]":
                    bracket_depth = max(0, bracket_depth - 1)
                elif ch == "(":
                    paren_depth += 1
                elif ch == ")":
                    paren_depth = max(0, paren_depth - 1)

        def _looks_like_gcode_boundary(s):
            first_line = s.lstrip(" \t\r\n").splitlines()[0] if s.strip() else ""
            return (
                first_line.startswith("[")
                or GCODE_BOUNDARY_OPTION.match(first_line) is not None
            )

        peek = tokenizer.peek()
        while peek:
            if peek.type == "whitespace":
                if peek.value.startswith("\n") and peek.value.endswith("\n"):
                    # Original rule: end multi-line value when newline isn't followed by indent.
                    # Extension: if we're inside a bracketed structure, keep going so we can see the closing brace.
                    if (brace_depth == 0 and bracket_depth == 0 and paren_depth == 0 and not in_sq and not in_dq):
                        # gcode block exception
                        if as_is:
                            next_text = tokenizer.slice.lstrip(" \t\r\n")

                            if _looks_like_gcode_boundary(next_text):
                                break

                            # Otherwise keep consuming gcode lines.
                            pass
                        elif not self._continues_after_comments(tokenizer, token=peek):
                            break
                        # else: only full-line comments separate us from more indented value
                    # else: we're inside {...}/(...)/[...] so don't break

                token = tokenizer.take("whitespace")
 
                # Ensure whitespace for empty options is tokenized in ValueLineNode (only newline is standalone)
                m = re.search(r"\r?\n", token.value)
                if m and m.start() > 0:
                    tokenizer.unread(token.value[m.start() :])
                    token.value = token.value[: m.start()]
 
                if len(body) == 0 and len(current_line) == 0 and len(current_entry) == 0:
                    current_line.append(WhitespaceNode(token.value))
                else:
                    current_entry += token.value
                    _scan_balance(token.value)
 
                idx = current_entry.find("\n")
                while idx != -1:
                    current_line.append(ValueEntryNode(current_entry[: idx + 1]))
                    current_entry = current_entry[idx + 1 :]
                    body.append(ValueLineNode(current_line))
                    current_line = []
                    idx = current_entry.find("\n")
 
            elif not as_is and peek.type == "comment":
                if len(current_entry) > 0:
                    current_line.append(ValueEntryNode(current_entry))
                    current_entry = ""
                current_line.append(self.parse_comment(tokenizer))

            # Escape hatch, so that a [section] token doesn't fall into the generic
            # else and get swallowed into the gcode value
            elif as_is and peek.type == "section":
                break

            # A comment's text is prose, not code: quotes/brackets inside it (e.g. a
            # contraction like "don't") must never affect the brace/bracket/paren/quote
            # balance used above to detect the end of the gcode value, or the value
            # swallows everything up to the next [section] - silently absorbing any
            # variable_* options that follow the gcode: line in the same section.
            elif as_is and peek.type == "comment":
                current_entry += next(tokenizer).value

            elif not as_is and peek.type == "placeholder":
                if len(current_entry) > 0:
                    current_line.append(ValueEntryNode(current_entry))
                    current_entry = ""
                current_line.append(self.parse_placeholder(tokenizer))
 
            elif peek.type == "template":
                t = tokenizer.take("template").value
                current_entry += t
                _scan_balance(t)
 
            else:
                v = next(tokenizer).value
                current_entry += v
                _scan_balance(v)
 
            peek = tokenizer.peek()
 
        if len(current_entry) > 0:
            current_line.append(ValueEntryNode(current_entry))
 
        if len(current_line) > 0:
            body.append(ValueLineNode(current_line))
 
        return body

    def parse_comment(self, tokenizer):
        token = tokenizer.take("comment")
        current_comment = token.value
        body = []

        peek = tokenizer.peek()
        while peek:
            if peek.type == "whitespace":
                if peek.value.find("\n") != -1:
                    break
                current_comment += tokenizer.take("whitespace").value
            elif peek.type == "placeholder":
                if len(current_comment) > 0:
                    body.append(CommentEntryNode(current_comment))
                    current_comment = ""
                body.append(self.parse_placeholder(tokenizer))
            else:
                current_comment += next(tokenizer).value

            peek = tokenizer.peek()

        if len(current_comment) > 0:
            body.append(CommentEntryNode(current_comment))

        return CommentNode(body)

    def parse_hidden_option_comment(self, tokenizer):
        token = tokenizer.take("hidden_option_comment")
        return HiddenOptionCommentNode(token.value)

    def parse_placeholder(self, tokenizer):
        placeholder = tokenizer.take("placeholder")
        return PlaceholderNode(placeholder.value[1:-1])

    def parse_whitespace(self, tokenizer):
        token = tokenizer.take("whitespace")
        return WhitespaceNode(token.value)

    def parse_template(self, tokenizer):
        token = tokenizer.take("template")
        return TemplateNode(token.value)


