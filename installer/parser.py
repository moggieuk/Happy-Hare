class ConfigSyntaxError(SyntaxError):
    """
    SyntaxError that also carries the bits needed to report/recover: a short one-line
    reason (no context block) plus the location it happened at.
    """

    def __init__(self, reason, line=None, col=None, origin=None, context=""):
        SyntaxError.__init__(self, "{} \n{}".format(reason, context))
        self.reason = reason
        self.line = line
        self.col = col
        self.origin = origin
        self.context = context


class Token(object):
    def __init__(self, type, value, line=None, col=None, pos=None, origin=None):
        self.type = type
        self.value = value
        self.line = line
        self.col = col
        self.pos = pos
        self.origin = origin

    def __repr__(self):
        return "{}: {}".format(self.type, self.value)


class Tokenizer(object):
    def __init__(self, buf, spec, origin=None):
        self.buf = buf
        self.slice = buf[:]
        self.next_token = None
        self.spec = spec
        self.origin = origin

        self.pos = 0
        self.line = 1
        self.col = 1

    def __iter__(self):
        return self

    def next(self):
        return self.__next__()

    def _recompute_line_col(self):
        if self.pos <= 0:
            self.line = 1
            self.col = 1
            return
        self.line = self.buf.count("\n", 0, self.pos) + 1
        last_nl = self.buf.rfind("\n", 0, self.pos)
        if last_nl == -1:
            self.col = self.pos + 1
        else:
            self.col = self.pos - last_nl

    def _format_error_context(self, line=None, col=None, origin=None, window=2):
        origin = origin if origin is not None else self.origin
        line = line if line is not None else self.line
        col = col if col is not None else self.col

        lines = self.buf.splitlines(True)  # keepends
        if not lines:
            loc = ""
            if origin:
                loc += "{}:".format(origin)
            loc += "{}:{}".format(line, col)
            return "  at {}\n".format(loc)

        idx = max(0, min(len(lines) - 1, line - 1))
        start = max(0, idx - window)
        end = min(len(lines), idx + window + 1)

        context = []
        for i in range(start, end):
            prefix = ">" if i == idx else " "
            txt = lines[i].rstrip("\n").rstrip("\r")
            context.append("{} {:4d} | {}".format(prefix, i + 1, txt))

        caret_pad = len("{} {:4d} | ".format(">", idx + 1))
        pointer = " " * (caret_pad + max(0, col - 1)) + "^"

        loc = ""
        if origin:
            loc += "{}:".format(origin)
        loc += "{}:{}".format(line, col)

        return "  at {}\n\n{}\n{}".format(loc, "\n".join(context), pointer)

    def __next__(self):
        if self.next_token is not None:
            next_token = self.next_token
            self.next_token = None
            return next_token

        if len(self.slice) == 0:
            raise StopIteration

        start_line = self.line
        start_col = self.col
        start_pos = self.pos

        for token_type, regex in self.spec:
            match = regex.match(self.slice)
            if match:
                value = match.group(0)

                # Advance absolute position counters
                self.pos += len(value)
                self._recompute_line_col()

                self.slice = self.slice[match.end() :]
                return Token(token_type, value, start_line, start_col, start_pos, self.origin)

        # Unknown/unmatchable byte (should be rare since 'unknown' exists, but keep defensive)
        ch = self.slice[0]
        raise ConfigSyntaxError(
            "Unexpected token '{}'".format(ch),
            start_line,
            start_col,
            self.origin,
            self._format_error_context(start_line, start_col, self.origin),
        )

    def peek(self):
        if self.next_token is None:
            try:
                self.next_token = next(self)
            except StopIteration:
                return None
        return self.next_token

    def take(self, token_type):
        try:
            token = next(self)
        except StopIteration:
            token = None  # end of file - report it like any other mismatch
        if token and token.type == token_type:
            return token
        else:
            got = token.type if token else "end of file"
            line = token.line if token else self.line
            col = token.col if token else self.col
            raise ConfigSyntaxError(
                "Expected {}, got {}".format(token_type, got),
                line,
                col,
                self.origin,
                self._format_error_context(line, col, self.origin),
            )

    def unread(self, s):
        if s:
            self.next_token = None
            self.slice = s + self.slice
            self.pos -= len(s)
            if self.pos < 0:
                self.pos = 0
            self._recompute_line_col()

    def consume(self, token_type):
        peek = self.peek()
        if peek and peek.type == token_type:
            self.take(token_type)

    def resync(self, start_pos, to_eof=False):
        """
        Error recovery. Rewind to `start_pos` (the start of the construct that failed) and
        swallow raw text up to the beginning of the next line that can start a fresh
        construct - a [section] header or an option assignment. The skipped text is
        returned so it can be preserved verbatim.

        At least the remainder of the failing line is always consumed, so the caller is
        guaranteed to make progress and cannot loop.
        """
        start_pos = max(0, min(start_pos, len(self.buf)))

        nl = self.buf.find("\n", start_pos)
        pos = len(self.buf) if nl == -1 else nl + 1
        while pos < len(self.buf) and not to_eof:
            nl = self.buf.find("\n", pos)
            line = self.buf[pos:] if nl == -1 else self.buf[pos:nl]
            if RESYNC_LINE.match(line):
                break
            pos = len(self.buf) if nl == -1 else nl + 1
        if to_eof:
            pos = len(self.buf)

        text = self.buf[start_pos:pos]
        self.next_token = None
        self.pos = pos
        self.slice = self.buf[pos:]
        self._recompute_line_col()
        return text


class Node(object):
    def __init__(self, type):
        self.type = type

    def _pretty_print(self, tab=4):
        def _print(node, lines, depth):
            lines.append(" " * depth * tab + type(node).__name__)
            for k, v in vars(node).items():
                if k in ["type", "body"]:
                    continue
                lines.append(unicode(" " * (depth + 1) * tab + "{}: `{}`").format(k, v))
            return True, lines

        lines = self.walk(_print, []) or []
        return unicode("\n".join(lines))

    def __str__(self):
        return self._pretty_print()

    def walk(self, callback, context=None, depth=0):
        _, context = callback(self, context, depth)
        return context

    def serialize(self):
        return unicode("")


class BodyNode(Node):
    def __init__(self, type, body):
        super(BodyNode, self).__init__(type)
        self.body = body

    def walk(self, callback, context=None, depth=0):
        cont, context = callback(self, context, depth)
        if cont:
            for item in self.body:
                context = item.walk(callback, context, depth + 1)
        return context


class DocumentNode(BodyNode):
    def __init__(self, body=None):
        super(DocumentNode, self).__init__("document", body or [])


class MagicExclusionNode(BodyNode):
    def __init__(self, body, origin=None):
        # All nodes after the magic comment live here
        BodyNode.__init__(self, "magic_exclusion", body)
        self.origin = origin


def _is_magic_comment_token(peek):
    return peek is not None and peek.type == "comment" and MAGIC_EXCLUSION_COMMENT.match(peek.value.lstrip())


class HiddenOptionCommentNode(Node):
    def __init__(self, value):
        Node.__init__(self, "hidden_option_comment")
        self.value = value

    def serialize(self):
        return self.value


class SectionNode(BodyNode):
    def __init__(self, name, body):
        BodyNode.__init__(self, "section", body)
        self.name = name

    def serialize(self):
        return unicode("[" + self.name + "]")


class OptionNode(BodyNode):
    def __init__(self, name, value, assign_op, trailing_ws=""):
        BodyNode.__init__(self, "option", value)
        self.name = name
        self.assign_op = assign_op
        self.trailing_ws = trailing_ws

    def serialize(self):
        return self.name + self.trailing_ws + self.assign_op

    def value(self, default=None, with_comments=False):
        if len(self.body) == 0:
            return default

        def serialize(node, buf, _):
            if not with_comments and isinstance(node, CommentNode):
                return False, buf
            return True, buf + node.serialize()

        value = ""
        for value_line in self.body:
            value = value_line.walk(serialize, value)
        return value.strip()


