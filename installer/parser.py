class ConfigBuilder(object):
    def __init__(self, filename=None, parser=Parser()):
        self.filename = filename
        self.parser = parser
        self.document = DocumentNode()
        if self.filename:
            with open(self.filename, "r") as f:
                # Pass the name so any parse error can say which file it was in
                self.document = self.parser.parse(f.read(), os.path.basename(self.filename))

    def read(self, filename, origin=None):
        with open(filename, "r") as f:
            doc = self.parser.parse(f.read(), origin)
            self.document.body += doc.body

    def read_buf(self, buf):
        doc = self.parser.parse(buf)
        self.document.body += doc.body

    def read_test(self, b):
        self.document.body = b

    # Dumps a tree view to stdout for debugging
    def pretty_print_document(self):
        def print_node(node, ctx, _):
            logging.debug(node._pretty_print())
            return True, ctx

        print(self.document._pretty_print())

    def write(self):
        def print_node(node, buffer, _):
            buffer += node.serialize()
            return True, buffer

        return self.document.walk(print_node, "")

    def parse_errors(self):
        """
        Return the UnparsedNode for every region that failed to parse, across all files
        read/merged into this document. Empty list means the config was fully understood.
        """

        def collect_unparsed(node, acc, _depth):
            if isinstance(node, UnparsedNode):
                acc.append(node)
            return True, acc

        return self.document.walk(collect_unparsed, [])

    def excluded_nodes(self, origin=None):
        """
        Return a list of all MagicExclusionNode instances in the current document,
        across all files that have been read/merged.
        """

        def collect_magic(node, acc, _depth):
            if isinstance(node, MagicExclusionNode) and (origin is None or node.origin == origin):
                acc.append(node)
            return True, acc  # Keep descending

        return self.document.walk(collect_magic, [])

    def delete_excluded(self, origin=None):
        """
        Remove every MagicExclusionNode (and all of its children) from the document.
        Returns the number of nodes removed.
        """
        to_remove = len(self.excluded_nodes(origin=origin))
        if to_remove == 0:
            return 0
        # Filter_tree prunes matching nodes and their entire subtree in-place
        self.parser.filter_tree(
            self.document, lambda n: isinstance(n, MagicExclusionNode) and (origin is None or n.origin == origin)
        )
        return to_remove

    def _iter_section_nodes(self, node, inside_excluded=False):
        """
        Yield (SectionNode, is_excluded) pairs from the tree rooted at `node`.
        Exclusion only flips to True when descending into a MagicExclusionNode.
        """
        if isinstance(node, SectionNode):
            yield node, inside_excluded
            return

        if isinstance(node, MagicExclusionNode):
            for child in node.body:
                # Descend with inside_excluded=True
                for pair in self._iter_section_nodes(child, True):
                    yield pair
            return

        if isinstance(node, DocumentNode):
            for child in node.body:
                # Reset inside_excluded at each top-level sibling (critical!)
                for pair in self._iter_section_nodes(child, False):
                    yield pair
            return

        # Other nodes cannot contain sections, so skip

    def _for_section(self, section_name, callback, ctx=None, scope="all"):
        """
        scope:
          - "included": only before the EXCLUDE marker
          - "excluded": only inside MagicExclusionNode
          - "all":      both
        """
        if scope not in ("all", "included", "excluded"):
            raise ValueError("scope must be 'all', 'included', or 'excluded'")

        out = ctx
        for sec, is_excl in self._iter_section_nodes(self.document, False):
            if section_name and sec.name != section_name:
                continue
            if scope == "included" and is_excl:
                continue
            if scope == "excluded" and not is_excl:
                continue
            out = callback(sec, out)
        return out

    def _get_section(self, section_name):
        section = self._for_section(section_name, identity)
        if section:
            return section
        else:
            raise KeyError("Section [{}] not found".format(section_name))

    def sections(self, scope="all"):
        sections = [x.name for x in self._for_section(None, collect, [], scope=scope)]
        return [x.name for x in self._for_section(None, collect, [], scope=scope)]

    def has_section(self, section_name):
        try:
            return self._get_section(section_name) is not None
        except KeyError:
            return False

    def _save_config_index(self):
        """Top-level index of Klipper's SAVE_CONFIG marker, or None if not present. Nothing
        may be inserted at or after this index"""
        for idx, node in enumerate(self.document.body):
            if isinstance(node, CommentNode):
                text = "".join(e.value for e in node.body if isinstance(e, CommentEntryNode))
                if SAVE_CONFIG_MARKER.match(text.lstrip()):
                    return idx
        return None

    def add_section(self, section_name, comment=None, at_top=False):
        if self.has_section(section_name):
            return

        # Newline after "[section]" header lives inside the section body,
        # matching how parse_section() stores it for parsed files
        section_body = [WhitespaceNode("\n")]
        document_body = []

        if comment:
            document_body.extend([
                CommentNode([CommentEntryNode("# " + comment)]),
                WhitespaceNode("\n"),
            ])

        document_body.append(SectionNode(section_name, section_body))

        if at_top:
            self.document.body[0:0] = document_body
        else:
            boundary_idx = self._save_config_index()

            # if not at_top and include, insert on next line
            inserted = False
            if section_name.startswith("include "):
                last_idx = None
                for idx, node in enumerate(self.document.body):
                    if boundary_idx is not None and idx >= boundary_idx:
                        break
                    if isinstance(node, SectionNode) and node.name.startswith("include "):
                        last_idx = idx

                if last_idx is not None:
                    insert_at = last_idx + 1

                    if insert_at < len(self.document.body):
                        node = self.document.body[insert_at]
                        if isinstance(node, CommentNode):
                            insert_at += 1
                            if (
                                insert_at < len(self.document.body)
                                and isinstance(self.document.body[insert_at], WhitespaceNode)
                                and re.search(r"\r\n|\n|\r", self.document.body[insert_at].value)
                            ):
                                insert_at += 1
                        elif isinstance(node, WhitespaceNode) and re.search(r"\r\n|\n|\r", node.value):
                            insert_at += 1

                    if boundary_idx is not None and insert_at > boundary_idx:
                        insert_at = boundary_idx

                    self.document.body[insert_at:insert_at] = document_body + [WhitespaceNode("\n")]
                    inserted = True

            # append to end if not inserted - but never at or after the SAVE_CONFIG marker
            if not inserted:
                if boundary_idx is not None:
                    self.document.body[boundary_idx:boundary_idx] = document_body + [WhitespaceNode("\n")]
                else:
                    self.document.body.append(WhitespaceNode("\n"))
                    self.document.body.extend(document_body)

    def remove_section(self, section_name):
        self.parser.filter_tree(
            self.document,
            lambda n: isinstance(n, SectionNode) and n.name == section_name,
        )

    def rename_section(self, section_name, new_section_name):
        self._for_section(section_name, rename, new_section_name)

    def _for_option(self, section_name, option_name, callback, ctx=None):
        def for_option(node, ctx, _):
            if isinstance(node, OptionNode) and (not option_name or node.name == option_name):
                ctx = callback(node, ctx)
            return (isinstance(node, SectionNode), ctx)

        section = self._get_section(section_name)
        return section.walk(for_option, ctx)

    def _options(self, section_name):
        return self._for_option(section_name, None, collect, [])

    def _get_option(self, section_name, option_name):
        option = self._for_option(section_name, option_name, identity)
        if option:
            return option
        else:
            raise KeyError("Option '{}' not found".format(option_name))

    def options(self, section_name):
        return [x.name for x in self._options(section_name)]

    def has_option(self, section_name, option_name):
        try:
            return self._for_option(section_name, option_name, identity) is not None
        except KeyError:
            return False

    def copy_option(self, src_config, section_name, option_name):
        option = src_config._get_option(section_name, option_name)
        section = self._get_section(section_name)

        cloned = OptionNode(option.name, copy.deepcopy(option.body), option.assign_op, option.trailing_ws)
        # Pull document-level tail (comments/whitespace after this section) back into the section (your existing behavior)

        doc_body = self.document.body
        try:
            sec_doc_idx = doc_body.index(section)
        except ValueError:
            sec_doc_idx = -1

        if sec_doc_idx != -1:
            j = sec_doc_idx + 1
            while j < len(doc_body) and isinstance(doc_body[j], (CommentNode, WhitespaceNode, HiddenOptionCommentNode)):
                j += 1
            if j > sec_doc_idx + 1:
                section.body.extend(doc_body[sec_doc_idx + 1 : j])
                del doc_body[sec_doc_idx + 1 : j]

        # Decide insertion point: after marker if present, else end
        insert_at = len(section.body)
        marker_idx = None
        for idx, node in enumerate(section.body):
            if isinstance(node, HiddenOptionCommentNode):
                marker_idx = idx

        if marker_idx is not None:
            insert_at = marker_idx + 1
        else:
            insert_at = len(section.body)

        # Ensure we don't tack onto previous line: add newline BEFORE cloned if needed, else AFTER
        nodes_to_insert = []
        if insert_at > 0 and not isinstance(section.body[insert_at - 1], WhitespaceNode):
            nodes_to_insert.append(WhitespaceNode("\n"))
            nodes_to_insert.append(cloned)
        else:
            nodes_to_insert.append(cloned)
            nodes_to_insert.append(WhitespaceNode("\n"))

        section.body[insert_at:insert_at] = nodes_to_insert

    def remove_option(self, section_name, option_name):
        try:
            section = self._get_section(section_name)
            for i, item in enumerate(section.body):
                if isinstance(item, OptionNode) and item.name == option_name:
                    section.body.pop(i)
        except KeyError:
            return

    def rename_option(self, section_name, option_name, new_option_name):
        self._for_option(section_name, option_name, rename, new_option_name)

    def get(self, section_name, option_name, default=None, with_comments=False):
        def serialize(node, buf, _):
            if not with_comments and isinstance(node, CommentNode):
                return False, buf
            return True, buf + node.serialize()

        try:
            option = self._get_option(section_name, option_name)
            if len(option.body) == 0:
                return default
            value = ""
            for value_line in option.body:
                value = value_line.walk(serialize, value)
            return value.strip()
        except KeyError:
            return default

    def getint(self, section_name, option_name, default=None):
        value = self.get(section_name, option_name)
        if value:
            return int(value.strip())
        return default

    def getfloat(self, section_name, option_name, default=None):
        value = self.get(section_name, option_name)
        if value:
            return float(value.strip())
        return default

    def getboolean(self, section_name, option_name, default=None):
        value = self.get(section_name, option_name)
        if value:
            return value.strip().lower() in ["1", "true", "yes", "on"]
        return default

    @staticmethod
    def _find_value_node(option):
        """
        Locate where an option's value text actually starts: the first ValueEntryNode holding
        something other than whitespace. Returns (line index, node), or (0, None) when the
        option carries no value text at all.

        Everything skipped on the way is layout that has to survive a set() - the "\\n" of a
        value that begins on the following line, a blank line, a commented out first entry.
        """
        for i, value_line in enumerate(option.body):
            for node in value_line.body:
                if isinstance(node, ValueEntryNode) and node.value.strip():
                    return i, node
        return 0, None

    def set(self, section_name, option_name, value):
        if value is None:
            logging.warning("{} in section [{}] has no value".format(option_name, section_name))
            value = ""
        value = value.strip()

#        # Neatly indent multi-line values (not required and breaks multi-line drying_data: {...})
#        idx = value.find("\n")
#        if idx != -1:
#            value = value[:idx] + re.sub(r"^(?=\S)", r"    ", value[idx:], flags=re.MULTILINE)

        # Overwrite where the value actually is, which is not always the first ValueEntryNode.
        # A value that starts on the line after the key leaves layout-only nodes in front of
        # it - a bare "\n", a blank line, a commented out first line - and writing over one
        # of those loses the line break ("a: \n    b" came back as "a: b") or, worse, joins
        # the value to a comment ("a: x# c", which configparser reads as the literal "x# c"
        # because an inline comment only counts when whitespace precedes it)
        if self.has_option(section_name, option_name):
            option = self._get_option(section_name, option_name)
            if option.body:
                target_line, target_node = self._find_value_node(option)

                if target_node is None:
                    # Nothing but layout, e.g. an option with no value at all. Put the value
                    # on the key line, ahead of any comment that is sitting there
                    vln = option.body[0]
                    if isinstance(vln.body[0], CommentNode):
                        vln.body.insert(0, ValueEntryNode(value))
                    else:
                        vln.body.append(ValueEntryNode(value))
                else:
                    # Keep the node's own indentation: it is the layout of the line the value
                    # lives on, not part of the value (which arrives here already stripped)
                    indent = target_node.value[: len(target_node.value) - len(target_node.value.lstrip(" \t"))]
                    target_node.value = indent + value

                    # Remove what is left of a multi-lined value, the new one replaces all of
                    # it. E.g.
                    #   [mmu_led_effect mmu_red_strobe]
                    #   layers:       strobe    1 1.5 add (1,1,1)
                    #                 breathing 2 0   difference (0.95,0,0) # animate
                    #                 static    0 0   top (1,0,0)
                    # Only lines after the one just written are candidates, so the layout in
                    # front of the value survives. A line whose ValueEntryNode is whitespace is
                    # retained because it is probably just carrying a comment. E.g.
                    # print_start_detection: 1   # ADVANCED: xxx
                    #                            # ADVANCED: yyy
                    # Side effects:
                    #  - comments on value lines after the value will be removed
                    #  - trailing whitespace on value will be removed (good thing)
                    for i in range(len(option.body) - 1, target_line, -1):
                        first = option.body[i].body[0]
                        if isinstance(first, ValueEntryNode) and first.value.strip() != '':
                            option.body.pop(i)

            else:
                body = self.parser.parse_value(Tokenizer(value, CONFIG_SPEC))
                option.body = body

        else:
            body = self.parser.parse_value(Tokenizer(" " + value, CONFIG_SPEC))
            section = self._get_section(section_name)
            section.body.append(OptionNode(option_name, body, self.parser.default_assign_op))
            section.body.append(WhitespaceNode("\n"))
            option = self._get_option(section_name, option_name)
            option.body = body

    def items(self, section_name):
        section = self._get_section(section_name)
        return [(item.name, item.value()) for item in section.body if isinstance(item, OptionNode)]

    def placeholders(self):
        def collect_placeholders(node, ctx, _):
            if isinstance(node, PlaceholderNode):
                ctx.append(node.value)
            return True, ctx

        return self.document.walk(collect_placeholders, [])


# Simple built-in command line round-trip test for the config parser. Use
# "--check" option to perform byte-by-byte comparison
# "--print" option to pretty print node tree
#
# Usage:
#   python parser.py path/to/printer.cfg <in.cfg>
#   python parser.py path/to/printer.cfg --out <path/to/out.cfg> <in.cfg>
#   python parser.py path/to/printer.cfg --check <in.cfg>
#
if __name__ == "__main__":
    import argparse
    import difflib
    import sys
    from pathlib import Path

    def _decode_with_fallback(data, forced_encoding):
        """
        Return (text, used_encoding). Prefers utf-8/utf-8-sig, falls back to latin-1.
        Preserves UTF-8 BOM by switching to 'utf-8-sig' when present.
        """
        if forced_encoding:
            return data.decode(forced_encoding), forced_encoding

        # Detect UTF-8 BOM
        if data.startswith(b"\xef\xbb\xbf"):
            return data.decode("utf-8-sig"), "utf-8-sig"

        # Try UTF-8, then latin-1
        try:
            return data.decode("utf-8"), "utf-8"
        except UnicodeDecodeError:
            return data.decode("latin-1"), "latin-1"

    def _encode_with_bom_awareness(text, used_encoding):
        if used_encoding == "utf-8-sig":
            # Prepend BOM when encoding (utf-8-sig handles it automatically)
            return text.encode("utf-8-sig")
        return text.encode(used_encoding)

    def _make_parser():
        ap = argparse.ArgumentParser(description="Parse a Klipper-style config and write it back unchanged.")
        ap.add_argument("cfg", type=Path, help="Input config file")
        ap.add_argument(
            "--out",
            type=Path,
            help="Path to write round-tripped output (default: <cfg>.roundtrip)",
        )
        ap.add_argument(
            "--check",
            action="store_true",
            help="Exit 0 if input == output bytes, else 1 and print unified diff.",
        )
        ap.add_argument(
            "--encoding",
            help="Force encoding for read/write (default: auto-detect utf-8/utf-8-sig, fallback latin-1)",
        )
        ap.add_argument(
            "--print",
            action="store_true",
            help="Dump a pretty print of node tree for debugging",
        )
        ap.add_argument(
            "--no-marker",
            action="store_true",
            help="Don't add '# HAPPY HARE PARSE ERROR' marker comments (keeps round trip byte-exact)",
        )
        ap.add_argument(
            "--strict",
            action="store_true",
            help="Abort on the first syntax error instead of recovering from it",
        )
        return ap

    def _main():
        args = _make_parser().parse_args()

        # Read original bytes (no newline normalization)
        try:
            original_bytes = args.cfg.read_bytes()
        except Exception as e:
            sys.stderr.write("[ERROR] Failed to read '{}': {}\n".format(args.cfg, e))
            sys.exit(2)

        # Decode with basic BOM/encoding handling
        try:
            original_text, used_encoding = _decode_with_fallback(original_bytes, forced_encoding=args.encoding)
        except Exception as e:
            sys.stderr.write("[ERROR] Decoding failed: {}\n".format(e))
            sys.exit(2)

        # Parse > serialize
        try:
            parser = Parser(recover=not args.strict, error_marker=not args.no_marker)
            builder = ConfigBuilder(parser=parser)
            builder.read_buf(original_text)
            roundtripped_text = builder.write()
        except Exception as e:
            sys.stderr.write("[ERROR] Parsing/serialization failed: {}\n".format(e))
            sys.exit(2)

        for node in builder.parse_errors():
            sys.stderr.write("[RECOVERED] line {}: {}\n".format(node.line, node.reason))

        # Encode output bytes (preserve BOM if used)
        try:
            out_bytes = _encode_with_bom_awareness(roundtripped_text, used_encoding)
        except Exception as e:
            sys.stderr.write("[ERROR] Encoding failed: {}\n".format(e))
            sys.exit(2)

        out_path = args.out or args.cfg.with_suffix(args.cfg.suffix + ".roundtrip")

        # Write exact bytes (no newline normalization)
        try:
            out_path.write_bytes(out_bytes)
        except Exception as e:
            sys.stderr.write("[ERROR] Failed writing '{}': {}\n".format(out_path, e))
            sys.exit(2)

        # Pretty print node structure for debugging
        if getattr(args, "print"):
            builder.pretty_print_document()

        if args.check:
            if original_bytes == out_bytes:
                print("OK: Round-trip is byte-for-byte identical.")
                sys.exit(0)
            else:
                print("MISMATCH: Round-trip differs. Unified diff:\n")
                # Decode both for human-friendly diff display
                # Use the same encoding we used to write (minus BOM for display)
                diff_from_enc = "utf-8" if used_encoding == "utf-8-sig" else used_encoding
                try:
                    lhs = original_bytes.decode(diff_from_enc, errors="replace")
                except Exception:
                    lhs = original_bytes.decode("latin-1", errors="replace")
                try:
                    rhs = out_bytes.decode(diff_from_enc, errors="replace")
                except Exception:
                    rhs = out_bytes.decode("latin-1", errors="replace")

                diff = difflib.unified_diff(
                    lhs.splitlines(keepends=True),
                    rhs.splitlines(keepends=True),
                    fromfile=str(args.cfg),
                    tofile=str(out_path),
                    n=3,
                )
                sys.stdout.writelines(diff)
                sys.exit(1)
        else:
            print("Wrote round-tripped file to: {}".format(out_path))

    _main()
